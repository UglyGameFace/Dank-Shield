create table public.guild_config_versions (
  version_id bigint generated by default as identity not null,
  guild_id text not null,
  config_table text not null default 'guild_configs'::text,
  snapshot jsonb not null,
  source text not null default 'database'::text,
  mode text,
  actor_id text,
  reason text,
  is_manual boolean not null default false,
  created_at timestamptz not null default now(),
  constraint guild_config_versions_pkey primary key (version_id)
);
